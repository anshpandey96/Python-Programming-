class Employee:
    name = "Ansh"
    language = "py"
    salary = 100000


Ansh = Employee()
print(Ansh.name, Ansh.language, Ansh.salary)
# Output: Ansh python 100000
# We can also change the attributes of the object

rohan = Employee()
rohan.name = "Rohan Roron Robinson"
print(rohan.name,rohan.salary, rohan.language)

# here name is object attribute and salary and language are class attributes  as they directly belong to the class .

